// Enum que define os estágios possíveis de uma startup
// Usado no StartupModel para indicar em que fase a empresa está
enum StageStartup {
  // Startup recém-criada, ainda em fase inicial de validação
  nova,
  // Startup que já está funcionando e gerando receita
  em_operacao,
  // Startup que já opera e está buscando crescer/escalar
  em_expansao,
}
